UPDATE public.profiles SET acesso_ofertas = true WHERE acesso_ofertas IS NULL;
UPDATE public.profiles SET acesso_pdv = false WHERE acesso_pdv IS NULL;

CREATE OR REPLACE FUNCTION public.can_access_offers()
RETURNS boolean LANGUAGE sql SECURITY DEFINER SET search_path=public STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = auth.uid() AND p.ativo = true
      AND (p.role = 'admin' OR p.acesso_ofertas = true)
  );
$$;

CREATE OR REPLACE FUNCTION public.can_access_pdv()
RETURNS boolean LANGUAGE sql SECURITY DEFINER SET search_path=public STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = auth.uid() AND p.ativo = true
      AND (p.role = 'admin' OR p.acesso_pdv = true)
  );
$$;

-- PDV
CREATE TABLE IF NOT EXISTS public.pdv_eventos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  data_evento date NOT NULL DEFAULT CURRENT_DATE,
  ativo boolean NOT NULL DEFAULT true,
  criado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.pdv_produtos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  preco numeric(12,2) NOT NULL DEFAULT 0 CHECK (preco >= 0),
  estoque integer NOT NULL DEFAULT 0 CHECK (estoque >= 0),
  ativo boolean NOT NULL DEFAULT true,
  criado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.pdv_vendas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evento_id bigint NOT NULL REFERENCES public.pdv_eventos(id) ON DELETE RESTRICT,
  numero text,
  forma_pagamento text NOT NULL DEFAULT 'dinheiro' CHECK (forma_pagamento IN ('dinheiro','pix','cartao','outro')),
  total numeric(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  status text NOT NULL DEFAULT 'finalizada' CHECK (status IN ('finalizada','cancelada')),
  criado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.pdv_itens_venda (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venda_id bigint NOT NULL REFERENCES public.pdv_vendas(id) ON DELETE CASCADE,
  produto_id bigint NOT NULL REFERENCES public.pdv_produtos(id) ON DELETE RESTRICT,
  quantidade integer NOT NULL CHECK (quantidade > 0),
  preco_unitario numeric(12,2) NOT NULL CHECK (preco_unitario >= 0),
  subtotal numeric(12,2) NOT NULL CHECK (subtotal >= 0)
);

CREATE INDEX IF NOT EXISTS idx_pdv_vendas_evento ON public.pdv_vendas(evento_id);
CREATE INDEX IF NOT EXISTS idx_pdv_itens_venda ON public.pdv_itens_venda(venda_id);

