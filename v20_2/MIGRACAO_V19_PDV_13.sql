-- Venda atômica: confere estoque, cria venda, cria itens e baixa estoque na mesma transação.
CREATE OR REPLACE FUNCTION public.registrar_venda_pdv(
  p_evento_id bigint,
  p_forma_pagamento text,
  p_itens jsonb
) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_venda_id bigint;
  v_total numeric(12,2) := 0;
  item jsonb;
  v_produto public.pdv_produtos%ROWTYPE;
  v_qtd integer;
  v_preco numeric(12,2);
BEGIN
  IF NOT public.can_access_pdv() THEN RAISE EXCEPTION 'Acesso ao PDV não autorizado'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.pdv_eventos WHERE id=p_evento_id AND ativo=true) THEN RAISE EXCEPTION 'Evento inválido ou inativo'; END IF;
  IF p_forma_pagamento NOT IN ('dinheiro','pix','cartao','outro') THEN RAISE EXCEPTION 'Forma de pagamento inválida'; END IF;
  IF jsonb_typeof(p_itens) <> 'array' OR jsonb_array_length(p_itens)=0 THEN RAISE EXCEPTION 'Venda sem itens'; END IF;

  FOR item IN SELECT * FROM jsonb_array_elements(p_itens) LOOP
    SELECT * INTO v_produto FROM public.pdv_produtos WHERE id=(item->>'produto_id')::bigint AND ativo=true FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Produto não encontrado'; END IF;
    v_qtd := (item->>'quantidade')::integer;
    IF v_qtd IS NULL OR v_qtd <= 0 THEN RAISE EXCEPTION 'Quantidade inválida'; END IF;
    IF v_produto.estoque < v_qtd THEN RAISE EXCEPTION 'Estoque insuficiente para: %', v_produto.nome; END IF;
    v_preco := v_produto.preco;
    v_total := v_total + (v_preco * v_qtd);
  END LOOP;

  INSERT INTO public.pdv_vendas(evento_id, numero, forma_pagamento, total, criado_por)
  VALUES(p_evento_id, NULL, p_forma_pagamento, v_total, auth.uid())
  RETURNING id INTO v_venda_id;
  UPDATE public.pdv_vendas SET numero = 'PDV-' || v_venda_id WHERE id=v_venda_id;

  FOR item IN SELECT * FROM jsonb_array_elements(p_itens) LOOP
    SELECT * INTO v_produto FROM public.pdv_produtos WHERE id=(item->>'produto_id')::bigint FOR UPDATE;
    v_qtd := (item->>'quantidade')::integer;
    INSERT INTO public.pdv_itens_venda(venda_id,produto_id,quantidade,preco_unitario,subtotal)
    VALUES(v_venda_id,v_produto.id,v_qtd,v_produto.preco,v_produto.preco*v_qtd);
    UPDATE public.pdv_produtos SET estoque=estoque-v_qtd, atualizado_em=now() WHERE id=v_produto.id;
  END LOOP;
  RETURN v_venda_id;
END; $$;

REVOKE ALL ON FUNCTION public.registrar_venda_pdv(bigint,text,jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.registrar_venda_pdv(bigint,text,jsonb) TO authenticated;

